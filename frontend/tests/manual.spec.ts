import { test, expect } from "@playwright/test";
import type { Page } from "@playwright/test";
async function setup(page: Page) {
  await page.goto("/");
  await page.getByRole("button", { name: "Começar minha DRE" }).click();
  await page.getByLabel("Nome da empresa").fill("Empresa Teste DRE");
  await page.getByLabel("Segmento").fill("Serviços");
  await page.getByLabel("Mês", { exact: true }).selectOption("8");
  await page.getByLabel("Ano", { exact: true }).fill("2026");
  await page.getByRole("button", { name: "Continuar", exact: true }).click();
  await expect(page.getByRole("heading", { name: "DRE — Agosto/2026" })).toBeVisible();
  return new URL(page.url()).searchParams.get("period");
}
async function add(page: Page, direction: "receita" | "saída", description: string, amount: string, category: string, sub?: string, date = "2026-08-10") {
  await page.getByRole("button", { name: `Adicionar ${direction}`, exact: true }).click();
  const dialog = page.getByRole("dialog", { name: `Adicionar ${direction}`, exact: true });
  await dialog.getByLabel("Data", { exact: true }).fill(date);
  await dialog.getByLabel("Competência", { exact: true }).fill("2026-08");
  await dialog.getByLabel("Descrição", { exact: true }).fill(description);
  await dialog.getByLabel("Valor", { exact: true }).fill(amount);
  await dialog.getByLabel("Categoria", { exact: true }).selectOption(category);
  if (sub) await dialog.getByLabel("Subcategoria", { exact: true }).selectOption({ label: sub });
  await dialog.getByRole("button", { name: "Salvar", exact: true }).click();
  await expect(dialog).not.toBeVisible();
}

test("four required transactions, exact totals, isolation and persistence", async ({ page, request }) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  const id = await setup(page);
  await page.getByRole("button", { name: "Começar pelas Receitas" }).click();
  await add(page, "receita", "Mensalidades", "100000", "REVENUE_RECURRING", undefined, "2026-08-05");
  await expect(page.getByRole("cell", { name: "Mensalidades", exact: true })).toBeVisible();
  await expect(page.locator(".summary")).toContainText("R$ 100.000,00");
  await page.getByRole("button", { name: "Saídas", exact: true }).click();
  await add(page, "saída", "Link IP", "20000", "COST", "Infraestrutura");
  await add(page, "saída", "Google Workspace", "1500", "EXPENSE", "Tecnologia");
  await add(page, "saída", "Servidor", "30000", "INVESTMENT", "Equipamentos");
  await expect(page.locator(".summary")).toContainText("R$ 51.500,00");
  await expect(page.getByRole("cell", { name: "Mensalidades", exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("heading", { name: "DRE — Agosto/2026" })).toBeVisible();
  await expect(page.getByRole("progressbar", { name: "Receitas" })).toHaveAttribute("aria-valuenow", "100");
  await expect(page.getByRole("progressbar", { name: "Saídas" })).toHaveAttribute("aria-valuenow", "100");
  await expect(page.getByText("Calculada", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "DRE", exact: true })).toBeEnabled();
  const revenues = (await (await request.get(`/api/periods/${id}/revenues`)).json()).data;
  const expenses = (await (await request.get(`/api/periods/${id}/expenses`)).json()).data;
  expect(revenues).toHaveLength(1); expect(expenses).toHaveLength(3);
  expect(revenues[0]).toMatchObject({ description: "Mensalidades", amount: "100000.00", direction: "IN" });
  expect(expenses.find((t: { description: string }) => t.description === "Servidor")).toMatchObject({ amount: "30000.00", dre_effect: "NO_EFFECT", include_in_dre: false });
  await page.getByRole("button", { name: "Saídas", exact: true }).click();
  for (const description of ["Link IP", "Google Workspace", "Servidor"]) await expect(page.getByRole("cell", { name: description, exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/m2-expenses.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

