  await page.getByRole("button", { name: "Configurações" }).click();
  let row = page.getByRole("row").filter({ hasText: "Ferramentas internas" });
  await row.getByRole("button", { name: "Editar" }).click();
  await page.getByRole("dialog").getByLabel("Nome", { exact: true }).fill("Ferramentas da equipe");
  await page.getByRole("button", { name: "Salvar subcategoria" }).click();
  row = page.getByRole("row").filter({ hasText: "Ferramentas da equipe" });
  await row.getByRole("button", { name: "Arquivar" }).click();
  await page.getByRole("button", { name: "Confirmar arquivamento" }).click();
