  await editor.getByRole("button", { name: "+ Criar nova subcategoria", exact: true }).click();
  const sub = page.getByRole("dialog", { name: "Nova subcategoria", exact: true });
  await sub.getByLabel("Nome", { exact: true }).fill("Ferramentas internas");
  await expect(sub.getByLabel("Categoria principal")).toBeDisabled();
  await sub.getByRole("button", { name: "Salvar subcategoria" }).click();
